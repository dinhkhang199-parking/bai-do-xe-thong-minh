test('background polling pauses while hidden and resumes once without leaking listeners', async () => {
  const timers = new Map(),
    listeners = new Set();
  let next = 0,
    runs = 0;
  const document = {
    hidden: false,
    addEventListener(type, fn) {
      listeners.add(fn);
    },
    removeEventListener(type, fn) {
      listeners.delete(fn);
    },
  };
  const ui = setup({
    document,
    setTimeout(fn) {
      const id = ++next;
      timers.set(id, fn);
      return id;
    },
    clearTimeout(id) {
      timers.delete(id);
    },
  });
  ui.ctx.task = () => {
    runs++;
  };
  vm.runInContext('this.poller=createVisibilityPoller();poller.schedule(task,5000)', ui.ctx);
  assert.equal(timers.size, 1);
  document.hidden = true;
  listeners.forEach((fn) => fn());
  assert.equal(timers.size, 0);
  document.hidden = false;
  listeners.forEach((fn) => fn());
  assert.equal(timers.size, 1);
  await [...timers.values()][0]();
  assert.equal(runs, 1);
  listeners.forEach((fn) => fn());
  assert.equal(runs, 1);
  ui.ctx.poller.dispose();
  assert.equal(listeners.size, 0);
});

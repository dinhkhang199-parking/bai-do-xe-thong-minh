function historySetup(handler) {
  const timers = new Map();
  let sequence = 0;
  const ui = setup({
    state: { view: 'payments', viewVersion: 1, user: { role: 'admin' } },
    emptyState: () => '',
    setTimeout(fn, delay) {
      const id = ++sequence;
      timers.set(id, {
        fn: () => {
          timers.delete(id);
          return fn();
        },
        delay,
      });
      return id;
    },
    clearTimeout(id) {
      timers.delete(id);
    },
    api: async (url, options) => {
      ui.calls.push({ url, options });
      if (url.startsWith('/payments?')) return { items: [], total: 0 };
      return handler(url, options);
    },
  });
  return Object.assign(ui, { timers, render: () => vm.runInContext('renderPayments()', ui.ctx) });
}


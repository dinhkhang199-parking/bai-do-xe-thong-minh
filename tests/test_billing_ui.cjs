function mbPageSetup(handler) {
  const timers = new Map();
  let sequence = 0;
  const ui = setup({
    state: { view: 'mb', viewVersion: 1, user: { role: 'admin' } },
    setTimeout(fn, delay) {
      const id = ++sequence;
      timers.set(id, {
        fn: () => {
          timers.delete(id);
          return fn();
        },
        delay,
      });
      return id;
    },
    clearTimeout(id) {
      timers.delete(id);
    },
    api: async (url, options) => {
      ui.calls.push({ url, options });
      return handler(url, options);
    },
  });
  return Object.assign(ui, { timers, render: () => vm.runInContext('renderMB()', ui.ctx) });
}
